def cards(items):
    out=[]
    for ico,t,d,b in items:
        badge=f'<span class="badge">{b}</span>' if b else ''
        out.append(f'<div class="card">{badge}<span class="ico" aria-hidden="true">{ico}</span><h3>{t}</h3><p>{d}</p></div>')
    return "\n                ".join(out)

def season_html(seasons):
    out=[]
    for name,months,note,best in seasons:
        cls=' best' if best is True else ''
        out.append(f'<div class="season{cls}"><b>{name}</b>{months}<small>{note}</small></div>')
    return "\n                ".join(out)

